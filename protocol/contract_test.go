package protocol

// Contract consistency tests: read testdata/contract_vectors.json and verify the current
// implementation entry by entry.
//
// This file has a **byte-identical** copy on each side, host (`pkg/protocol` in the runtime
// repository) and SDK (`protocol/` in the SDK repository), and so does the vector file. Both
// implementations run the same vectors, so:
//
//   - whoever changes semantics (parsing rules, containment matrix, key table, template
//     names, frame types, response codes) goes red here first;
//   - when a change is "intentional", the vector file must be updated and ContractVersion
//     bumped at the same time — one explicit action.
//
// The vector file is generated by the implementation (freezing the status quo), so it
// describes the "current contract", not the "ideal contract".

import (
	"encoding/json"
	"os"
	"path/filepath"
	"sort"
	"testing"
)

type contractVectors struct {
	ContractVersion int      `json:"contract_version"`
	ScopeSpaces     []string `json:"scope_spaces"`
	ScopeKeys       []struct {
		Key string `json:"key"`
		Dir string `json:"dir"`
	} `json:"scope_keys"`
	ScopeParse []struct {
		Raw    string `json:"raw"`
		Space  string `json:"space"`
		Key    string `json:"key"`
		Sub    string `json:"sub"`
		Whole  bool   `json:"whole"`
		String string `json:"string"`
	} `json:"scope_parse"`
	ScopeInvalid  []string `json:"scope_parse_invalid"`
	ScopeContains []struct {
		Outer string `json:"outer"`
		Inner string `json:"inner"`
		Want  bool   `json:"want"`
	} `json:"scope_contains"`
	UFIPoolRel []struct {
		UFI string `json:"ufi"`
		Rel string `json:"rel"`
	} `json:"ufi_pool_rel"`
	PathWithin []struct {
		Base   string `json:"base"`
		Target string `json:"target"`
		Want   bool   `json:"want"`
	} `json:"path_within"`
	Templates []struct {
		Template       string `json:"template"`
		Mode           string `json:"mode"`
		DaemonProvided bool   `json:"daemon_provided"`
		AcceptFile     bool   `json:"accept_file"`
	} `json:"templates"`
	MountTable struct {
		FileName     string   `json:"file_name"`
		Version      int      `json:"version"`
		ContainerDir string   `json:"container_dir"`
		EnvKey       string   `json:"env_key"`
		UFIPrefix    string   `json:"ufi_prefix"`
		JSONKeys     []string `json:"json_keys"`
	} `json:"mount_table"`
	Wire struct {
		MessageTypes []string `json:"message_types"`
		FrameTypes   []string `json:"frame_types"`
		CodeSuccess  string   `json:"code_success"`
		CodeError    string   `json:"code_error"`
	} `json:"wire"`
	Runtime struct {
		ContainerRuntimeKind string `json:"container_runtime_kind"`
	} `json:"runtime"`
}

func loadContractVectors(t *testing.T) contractVectors {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", "contract_vectors.json"))
	if err != nil {
		t.Fatalf("failed to read the contract vectors (both copies must carry this file): %v", err)
	}
	var vectors contractVectors
	if err := json.Unmarshal(raw, &vectors); err != nil {
		t.Fatalf("failed to parse the contract vectors: %v", err)
	}
	return vectors
}

func TestContractVersionMatchesVectors(t *testing.T) {
	vectors := loadContractVectors(t)
	if vectors.ContractVersion != ContractVersion {
		t.Fatalf("ContractVersion=%d does not match %d in the vectors file: a semantic change must bump the version and update the vectors together",
			ContractVersion, vectors.ContractVersion)
	}
}

func TestContractScopeSpaces(t *testing.T) {
	vectors := loadContractVectors(t)
	want := []string{string(ScopeSpaceApp), string(ScopeSpaceAll), string(ScopeSpaceOwn)}
	if len(vectors.ScopeSpaces) != len(want) {
		t.Fatalf("the number of space axes changed: vectors %v, implementation %v", vectors.ScopeSpaces, want)
	}
	for i := range want {
		if vectors.ScopeSpaces[i] != want[i] {
			t.Errorf("space axis [%d]: vectors %q, implementation %q", i, vectors.ScopeSpaces[i], want[i])
		}
	}
}

func TestContractScopeKeyTable(t *testing.T) {
	vectors := loadContractVectors(t)
	names := ScopeKeyNames()
	if len(names) != len(vectors.ScopeKeys) {
		t.Fatalf("the number of directory keys changed: vectors %d, implementation %d", len(vectors.ScopeKeys), len(names))
	}
	for i, entry := range vectors.ScopeKeys {
		if names[i] != entry.Key {
			t.Errorf("key[%d]: vectors %q, implementation %q", i, entry.Key, names[i])
		}
		dir, ok := ScopeKeyDir(entry.Key)
		if !ok || dir != entry.Dir {
			t.Errorf("ScopeKeyDir(%q) = %q,%v, vectors %q", entry.Key, dir, ok, entry.Dir)
		}
	}
}

func TestContractScopeParse(t *testing.T) {
	vectors := loadContractVectors(t)
	for _, tc := range vectors.ScopeParse {
		got, err := ParseScopeValue(tc.Raw)
		if err != nil {
			t.Errorf("ParseScopeValue(%q) returned an error: %v", tc.Raw, err)
			continue
		}
		if string(got.Space) != tc.Space || got.Key != tc.Key || got.Sub != tc.Sub {
			t.Errorf("ParseScopeValue(%q) = %+v, vectors space=%q key=%q sub=%q",
				tc.Raw, got, tc.Space, tc.Key, tc.Sub)
		}
		if got.WholeSpace() != tc.Whole {
			t.Errorf("ParseScopeValue(%q).WholeSpace() = %v, vectors %v", tc.Raw, got.WholeSpace(), tc.Whole)
		}
		if got.String() != tc.String {
			t.Errorf("ParseScopeValue(%q).String() = %q, vectors %q", tc.Raw, got.String(), tc.String)
		}
	}
	for _, raw := range vectors.ScopeInvalid {
		if _, err := ParseScopeValue(raw); err == nil {
			t.Errorf("ParseScopeValue(%q) should report an error (the vectors pin this syntax as invalid)", raw)
		}
	}
}

func TestContractScopeContains(t *testing.T) {
	vectors := loadContractVectors(t)
	for _, tc := range vectors.ScopeContains {
		outer, err := ParseScopeValue(tc.Outer)
		if err != nil {
			t.Errorf("parse %q: %v", tc.Outer, err)
			continue
		}
		inner, err := ParseScopeValue(tc.Inner)
		if err != nil {
			t.Errorf("parse %q: %v", tc.Inner, err)
			continue
		}
		if got := outer.Contains(inner); got != tc.Want {
			t.Errorf("%q.Contains(%q) = %v, vectors %v", tc.Outer, tc.Inner, got, tc.Want)
		}
	}
}

func TestContractUFIAndPath(t *testing.T) {
	vectors := loadContractVectors(t)
	for _, tc := range vectors.UFIPoolRel {
		rel, ok := UFIPoolRel(tc.UFI)
		if !ok {
			rel = ""
		}
		if rel != tc.Rel {
			t.Errorf("UFIPoolRel(%q) = %q,%v, vectors rel=%q", tc.UFI, rel, ok, tc.Rel)
		}
	}
	for _, tc := range vectors.PathWithin {
		if got := PathWithin(tc.Base, tc.Target); got != tc.Want {
			t.Errorf("PathWithin(%q, %q) = %v, vectors %v", tc.Base, tc.Target, got, tc.Want)
		}
	}
}

// TestContractTemplateCatalog freezes the **names and modes** of capability templates:
// applications and the runtime converse through these names, so renaming or changing a mode
// breaks compatibility.
func TestContractTemplateCatalog(t *testing.T) {
	vectors := loadContractVectors(t)
	catalog := Catalog()
	if len(catalog) != len(vectors.Templates) {
		t.Fatalf("the number of templates changed: vectors %d, implementation %d", len(vectors.Templates), len(catalog))
	}
	byTemplate := make(map[string]Capability, len(catalog))
	for _, capability := range catalog {
		byTemplate[capability.Template] = capability
	}
	for _, want := range vectors.Templates {
		got, ok := byTemplate[want.Template]
		if !ok {
			t.Errorf("template %q is in the vectors but missing from the implementation", want.Template)
			continue
		}
		if string(got.Mode) != want.Mode {
			t.Errorf("template %q changed mode: vectors %q, implementation %q", want.Template, want.Mode, got.Mode)
		}
		if got.DaemonProvided != want.DaemonProvided {
			t.Errorf("template %q changed daemon_provided: vectors %v, implementation %v",
				want.Template, want.DaemonProvided, got.DaemonProvided)
		}
		if got.AcceptFile != want.AcceptFile {
			t.Errorf("template %q changed accept_file: vectors %v, implementation %v",
				want.Template, want.AcceptFile, got.AcceptFile)
		}
	}
}

func TestContractMountTableAndWire(t *testing.T) {
	vectors := loadContractVectors(t)

	if MountTableFileName != vectors.MountTable.FileName ||
		MountTableVersion != vectors.MountTable.Version ||
		ContainerResourceDir != vectors.MountTable.ContainerDir ||
		EnvMountTable != vectors.MountTable.EnvKey ||
		UFIPoolPrefix != vectors.MountTable.UFIPrefix {
		t.Errorf("mount table constants changed: implementation %q/%d/%q/%q/%q, vectors %q/%d/%q/%q/%q",
			MountTableFileName, MountTableVersion, ContainerResourceDir, EnvMountTable, UFIPoolPrefix,
			vectors.MountTable.FileName, vectors.MountTable.Version, vectors.MountTable.ContainerDir,
			vectors.MountTable.EnvKey, vectors.MountTable.UFIPrefix)
	}

	zero, err := json.Marshal(MountTable{})
	if err != nil {
		t.Fatal(err)
	}
	var probe map[string]any
	if err := json.Unmarshal(zero, &probe); err != nil {
		t.Fatal(err)
	}
	if len(probe) != len(vectors.MountTable.JSONKeys) {
		t.Errorf("the number of mount table fields changed: vectors %v, implementation %d", vectors.MountTable.JSONKeys, len(probe))
	}
	for _, key := range vectors.MountTable.JSONKeys {
		if _, ok := probe[key]; !ok {
			t.Errorf("mount table is missing field %q (the runtime writes it, the app reads it: the name is part of the contract)", key)
		}
	}

	messageTypes := []string{string(TypeCall), string(TypeSubscribe), string(TypeUnsubscribe), string(TypePing)}
	sort.Strings(messageTypes)
	if len(messageTypes) != len(vectors.Wire.MessageTypes) {
		t.Errorf("the number of message types changed: vectors %v, implementation %v", vectors.Wire.MessageTypes, messageTypes)
	}
	for i := range messageTypes {
		if i < len(vectors.Wire.MessageTypes) && messageTypes[i] != vectors.Wire.MessageTypes[i] {
			t.Errorf("message type [%d]: vectors %q, implementation %q", i, vectors.Wire.MessageTypes[i], messageTypes[i])
		}
	}
	frameTypes := []string{string(FrameResponse), string(FrameEvent), string(FramePong)}
	sort.Strings(frameTypes)
	if len(frameTypes) != len(vectors.Wire.FrameTypes) {
		t.Errorf("the number of frame types changed: vectors %v, implementation %v", vectors.Wire.FrameTypes, frameTypes)
	}
	for i := range frameTypes {
		if i < len(vectors.Wire.FrameTypes) && frameTypes[i] != vectors.Wire.FrameTypes[i] {
			t.Errorf("frame type [%d]: vectors %q, implementation %q", i, vectors.Wire.FrameTypes[i], frameTypes[i])
		}
	}
	if CodeSuccess != vectors.Wire.CodeSuccess || CodeError != vectors.Wire.CodeError {
		t.Errorf("response codes changed: implementation %q/%q, vectors %q/%q",
			CodeSuccess, CodeError, vectors.Wire.CodeSuccess, vectors.Wire.CodeError)
	}
	if ContainerRuntimeKind != vectors.Runtime.ContainerRuntimeKind {
		t.Errorf("container runtime kind changed: implementation %q, vectors %q",
			ContainerRuntimeKind, vectors.Runtime.ContainerRuntimeKind)
	}
}
