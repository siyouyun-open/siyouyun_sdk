// Package protocol defines the wire protocol and capability catalog of the minictl
// capability bus.
//
// It is the **single source of truth** for the contract between the SDK and the daemon:
// message frames, template names, modes, response codes, and injected environment variable
// names all live here; if each side keeps its own copy of the strings, mismatches like
// "the SDK sends A, the daemon expects B" are bound to appear — the kind that only shows up
// on a real device.
//
// This package deliberately has zero third-party dependencies: a native application pulls
// in the contract on its own and nothing else from the runtime.
package protocol

import "encoding/json"

// MessageType is the message type from client to daemon.
type MessageType string

const (
	// TypeCall synchronously calls a capability template.
	TypeCall MessageType = "call"
	// TypeSubscribe subscribes to event topics.
	TypeSubscribe MessageType = "subscribe"
	// TypeUnsubscribe cancels a subscription.
	TypeUnsubscribe MessageType = "unsubscribe"
	// TypePing is an application-level heartbeat, used for end-to-end liveness checks.
	TypePing MessageType = "ping"
)

// FrameType is the message type from daemon to client.
type FrameType string

const (
	// FrameResponse is the reply to call / subscribe / unsubscribe, matched to a request by ID.
	FrameResponse FrameType = "response"
	// FrameEvent is a subscription push.
	FrameEvent FrameType = "event"
	// FramePong is the reply to ping.
	FramePong FrameType = "pong"
)

// Request is a message the client sends to the bus.
//
// It shares the same shape across the WS / UDS transports: UDS JSON-lines puts one object
// per line, WS puts one object per text frame.
type Request struct {
	Type MessageType `json:"type"`
	// ID is generated by the client and used to match replies back to requests; it must be
	// unique within a connection.
	ID string `json:"id"`
	// Template is the capability template (see templates.go).
	Template string `json:"template,omitempty"`
	// Signature is the signature of custom-domain (custom.*) capabilities.
	// Built-in templates are resolved by the daemon itself and do not need it; a missing
	// custom.* signature is rejected directly by the protocol layer.
	Signature string `json:"signature,omitempty"`
	// ProviderAppID pins the call to a specific provider App (optional).
	ProviderAppID string `json:"provider_app_id,omitempty"`
	// Payload is the capability's own input arguments.
	Payload json.RawMessage `json:"payload,omitempty"`
	// Headers are forwarded to the provider; they must not be used to forge caller identity
	// headers.
	Headers map[string]string `json:"headers,omitempty"`
	// Topics is the topic list for subscribe / unsubscribe.
	Topics []string `json:"topics,omitempty"`
}

// Response is the bus's reply to a Request; it is also used for event pushes.
type Response struct {
	Type FrameType `json:"type"`
	// ID corresponds to the request's ID; for event pushes it is a daemon-generated timestamp.
	// omitempty is deliberately omitted: replies to malformed requests have no ID, but an
	// empty string is still given explicitly, keeping byte-for-byte compatibility with the
	// existing wire format.
	ID string `json:"id"`
	// Code is the response code (see codes.go).
	Code string `json:"code,omitempty"`
	// Data is the payload of a successful reply.
	Data json.RawMessage `json:"data,omitempty"`
	// Topic / Event are used only for event pushes.
	Topic string          `json:"topic,omitempty"`
	Event json.RawMessage `json:"event,omitempty"`
	// Error is the failure reason; present when Code is A00400.
	Error string `json:"error,omitempty"`
}

// Event is a parsed event push.
type Event struct {
	Topic string
	Data  json.RawMessage
}
