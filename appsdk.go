// Package appsdk is the entry point for AppStore apps onto the minictl capability
// bus; native host processes and containerized apps share the same API.
//
// It does only three things:
//
//  1. Normalize the runtime environment injected by the platform into a typed
//     Runtime (see FromEnv for the two runtime forms);
//  2. Use that information to build the bus client and wrap the capabilities;
//  3. Wire up "logical addressing → local absolute path" resolution through the
//     fs subpackage (both sides are plain POSIX).
//
// It does **not** provide a Web framework, impose a directory structure, or panic
// at initialization time: an app is an ordinary process (or container), and the
// SDK should not decide its process shape. When the bus is temporarily
// unavailable the app should still start normally and degrade on its own — leave
// failures to the specific capability calls, not to startup.
package appsdk

import (
	"log"
	"os"
	"strconv"
	"strings"
	"sync"

	"github.com/siyouyun-open/siyouyun_sdk/v2/bus"
	"github.com/siyouyun-open/siyouyun_sdk/v2/capability"
	appfs "github.com/siyouyun-open/siyouyun_sdk/v2/fs"
	"github.com/siyouyun-open/siyouyun_sdk/v2/protocol"
)

// Runtime is a snapshot of the runtime environment the platform injects into an
// app process.
//
// The same struct carries both runtime forms (native host process / container):
// the field semantics are identical, only the sources differ, and FromEnv
// normalizes them. Use IsNative / IsContainer to tell them apart instead of
// making callers guess from environment variables.
type Runtime struct {
	// AppID is the app id (file event topics are scoped by it).
	AppID string
	// AppCode is the install directory name; a container only has the app id, so
	// this value equals AppID.
	AppCode string
	// InstanceID is the stable instance id; for containers it is generated by the
	// deployment and the SDK cannot read it from the environment.
	InstanceID string
	// Namespace is the space the instance belongs to: native is always default
	// (shared host process), while a container is the user space it was deployed
	// into.
	Namespace string
	// Username is the username that owns the space; native requires the caller to
	// supply it when an explicit scope is needed, while a container can (and only
	// it can) derive it from the environment.
	Username string
	// RuntimeKind is the runtime kind (native / runc).
	RuntimeKind string

	// Endpoint / Port are this app's own listen address (allocated by the daemon).
	Endpoint string
	Port     int

	// InstallRoot is the install directory (versioned); StaticRoot is the static
	// asset directory.
	InstallRoot string
	StaticRoot  string
	// InstallSpace is the storage space chosen by the user (may be empty).
	InstallSpace string
	// DataDir is the platform-managed data directory; empty when storage.app.file
	// is not declared.
	DataDir string

	// BusSocket / BusHTTP / BusWS are the bus's three entry points.
	BusSocket string
	BusHTTP   string
	BusWS     string
	// CallerToken is the caller token issued by the daemon (used only to identify
	// the caller).
	CallerToken string
	// MountTable is the mount table file path (injected by the daemon after
	// storage.* is declared); empty means there is no directly accessible local
	// directory.
	MountTable string

	// StoragePools are the storage pools exposed by storage.user.file: normalized
	// name -> host absolute path. The normalization rules match the daemon's
	// (uppercase, non-alphanumeric to underscore), so it is not reversible; use
	// FindStoragePool to look up a pool by its original name.
	StoragePools map[string]string
}

// FromEnv reads the current process environment. A missing field is never an
// error: callers use Managed() to tell whether they are running under the
// platform-managed app runtime.
//
// Both the native and the container variable sets are recognized and normalized
// into the same Runtime:
//
//	native    MINI_APP_* (including instance ID, install directory, caller token, mount table path)
//	container APP_RUNTIME=RUNC / APPCODE / MINI_NAMESPACE / MINI_USERNAME,
//	          the bus socket is fixed at /bus/app.sock, the mount table at an agreed path inside the container
func FromEnv() Runtime {
	port, _ := strconv.Atoi(strings.TrimSpace(os.Getenv(protocol.EnvPort)))
	runtimeKind := normalizeRuntimeKind(os.Getenv(protocol.EnvRuntime), os.Getenv(protocol.EnvContainerRuntime))

	appCode := firstNonEmpty(os.Getenv(protocol.EnvCode), os.Getenv(protocol.EnvAppCode))
	appID := strings.TrimSpace(os.Getenv(protocol.EnvAppID))
	// A container only injects APPCODE, and its value is the app id (see runtime.GetDefaultConfig).
	if appID == "" && runtimeKind == protocol.ContainerRuntimeKind {
		appID = appCode
	}

	busSocket := strings.TrimSpace(os.Getenv(protocol.EnvBusSocket))
	if busSocket == "" && runtimeKind == protocol.ContainerRuntimeKind {
		// The in-container path is part of the deployment contract and needs no
		// environment variable to announce it.
		busSocket = protocol.EnvContainerBusSocket
	}

	return Runtime{
		AppID:        appID,
		AppCode:      appCode,
		InstanceID:   strings.TrimSpace(os.Getenv(protocol.EnvInstanceID)),
		Namespace:    firstNonEmpty(os.Getenv(protocol.EnvNamespace), os.Getenv(protocol.EnvLegacyNamespace)),
		Username:     strings.TrimSpace(os.Getenv(protocol.EnvContainerUsername)),
		RuntimeKind:  runtimeKind,
		Endpoint:     strings.TrimSpace(os.Getenv(protocol.EnvEndpoint)),
		Port:         port,
		InstallRoot:  strings.TrimSpace(os.Getenv(protocol.EnvInstallRoot)),
		StaticRoot:   strings.TrimSpace(os.Getenv(protocol.EnvStaticRoot)),
		InstallSpace: strings.TrimSpace(os.Getenv(protocol.EnvInstallSpace)),
		DataDir:      strings.TrimSpace(os.Getenv(protocol.EnvDataDir)),
		BusSocket:    busSocket,
		BusHTTP:      strings.TrimSpace(os.Getenv(protocol.EnvBusHTTP)),
		BusWS:        strings.TrimSpace(os.Getenv(protocol.EnvBusWS)),
		CallerToken:  strings.TrimSpace(os.Getenv(protocol.EnvCallerToken)),
		MountTable:   strings.TrimSpace(os.Getenv(protocol.EnvMountTable)),
		StoragePools: readStoragePools(),
	}
}

// normalizeRuntimeKind normalizes the runtime kind variables from both sides
// into lowercase values.
//
// MINI_APP_RUNTIME takes precedence (an explicit native declaration), followed by
// the container's APP_RUNTIME=RUNC.
func normalizeRuntimeKind(miniRuntime, containerRuntime string) string {
	if v := strings.ToLower(strings.TrimSpace(miniRuntime)); v != "" {
		return v
	}
	if strings.EqualFold(strings.TrimSpace(containerRuntime), protocol.RuntimeContainer) {
		return protocol.ContainerRuntimeKind
	}
	return strings.ToLower(strings.TrimSpace(containerRuntime))
}

// IsNative reports that the current instance is a platform-managed native host
// process.
func (r Runtime) IsNative() bool { return r.RuntimeKind == protocol.RuntimeNative }

// IsContainer reports that the current instance runs in a container.
//
// The criterion is APP_RUNTIME=RUNC, not "MINI_NAMESPACE is present": the latter
// also showed up in the old native implementation, and using it as the criterion
// would conflate the two forms.
func (r Runtime) IsContainer() bool { return r.RuntimeKind == protocol.ContainerRuntimeKind }

// Managed reports whether the current process is hosted by the platform runtime.
// When it is false (local development, unit tests) the SDK is still usable, but
// the bus addresses must be configured explicitly.
func (r Runtime) Managed() bool {
	return r.RuntimeKind != "" || r.BusSocket != "" || r.BusHTTP != "" || r.BusWS != ""
}

// HasBus reports whether at least one bus entry point is configured.
func (r Runtime) HasBus() bool {
	return r.BusSocket != "" || r.BusHTTP != "" || r.BusWS != ""
}

// DefaultScope is the user scope this instance "itself belongs to".
//
// native returns an empty scope: it is a shared host process whose connection
// namespace is always default, so the user cannot be derived and must be given
// explicitly by the caller (see docs/technical/APPSDK.md §4).
//
// A container returns the space it was deployed into. Note that Namespace is a
// **user space suffix**, not the full deployment space name: the deployment space
// is {username}-{namespace} (e.g. admin1-main), whereas the capability API wants
// username=admin1 + namespace=main. Passing the full name as namespace produces
// admin1-admin1-main, which the daemon rejects outright (once authorization
// validation is added) — this is exactly how it surfaced in a real-machine
// regression. When username does not match the deployment space prefix, leave
// namespace empty and let the daemon derive it from the connection.
func (r Runtime) DefaultScope() capability.Scope {
	if !r.IsContainer() {
		return capability.Scope{}
	}
	username := strings.TrimSpace(r.Username)
	space := strings.TrimSpace(r.Namespace)
	userNamespace := ""
	if username != "" && strings.HasPrefix(space, username+"-") {
		userNamespace = strings.TrimPrefix(space, username+"-")
	}
	return capability.Scope{Username: username, Namespace: userNamespace}
}

// FindStoragePool looks up the host path by pool name (names are compared using
// the daemon's normalization rules).
func (r Runtime) FindStoragePool(name string) (string, bool) {
	key := normalizePoolName(name)
	if key == "" {
		return "", false
	}
	path, ok := r.StoragePools[key]
	return path, ok
}

// BusOptions builds the bus client configuration from the runtime environment.
func (r Runtime) BusOptions() bus.Options {
	return bus.Options{
		SocketPath:  r.BusSocket,
		WSURL:       r.BusWS,
		HTTPURL:     r.BusHTTP,
		CallerToken: r.CallerToken,
		// The bus ships its own logging interface, but the default implementation
		// is a no-op. Leaving it unwired means dropping key signals such as "the
		// connection is down, reconnecting, reconnect failed, subscription replay
		// failed" — on a real machine this looks like "events suddenly stop
		// arriving and there is nothing in the log" (measured 2026-09-22: after the
		// daemon restarted the app never received another event, while the app log
		// gave no hint of its relationship to the bus). Here it is wired to the
		// standard logger so apps do not each have to remember to set it.
		Logger: func(format string, args ...any) { log.Printf(format, args...) },
	}
}

// App is a native app that has been connected to the bus.
type App struct {
	Runtime Runtime

	client *bus.Client
	caps   *capability.Client

	mu    sync.Mutex
	state bus.State

	fsMu     sync.Mutex
	fsTable  *appfs.Table
	fsErr    error
	fsLoaded bool
}

// New reads the environment, creates the bus client, and binds the capabilities.
//
// It does not establish a connection (that happens on the first call) and does
// not fail because the environment is missing: calls return explicit errors
// instead.
func New() *App {
	return NewWithOptions(FromEnv())
}

// NewWithOptions creates an App from the given environment (convenient for unit
// tests and custom configuration sources). When the bus addresses in the
// environment are empty, opts can override them.
func NewWithOptions(runtime Runtime, opts ...Option) *App {
	options := runtime.BusOptions()
	for _, opt := range opts {
		opt(&options)
	}

	app := &App{Runtime: runtime}
	app.state = bus.State{Transport: "none"}
	options.OnStateChange = func(state bus.State) {
		app.mu.Lock()
		app.state = state
		app.mu.Unlock()
	}
	app.client = bus.New(options)
	app.caps = capability.New(app.client)
	// Local filtering of file events needs to know "this instance's authorized
	// spaces": the space-axis check for `space.*` scope must use the authorized
	// spaces (native gets them from the mount table) as its baseline, not the
	// event's own space — the latter is always true.
	app.caps.Events().WithSpaces(func() []string {
		table, err := app.FS()
		if err != nil || table == nil {
			return nil
		}
		return table.Spaces()
	})
	return app
}

// Option overrides the bus client configuration (for example specifying the bus
// address manually during local development).
type Option func(*bus.Options)

// WithBusSocket overrides the UDS path.
func WithBusSocket(path string) Option {
	return func(o *bus.Options) { o.SocketPath = path }
}

// WithBusHTTP overrides the HTTP base URL.
func WithBusHTTP(baseURL string) Option {
	return func(o *bus.Options) { o.HTTPURL = baseURL }
}

// WithBusWS overrides the WS URL.
func WithBusWS(url string) Option {
	return func(o *bus.Options) { o.WSURL = url }
}

// WithCallerToken overrides the caller token.
func WithCallerToken(token string) Option {
	return func(o *bus.Options) { o.CallerToken = token }
}

// Bus returns the underlying bus client.
func (a *App) Bus() *bus.Client { return a.client }

// Capabilities returns the capability facade.
func (a *App) Capabilities() *capability.Client { return a.caps }

// KV returns the KV capability.
func (a *App) KV() *capability.KV { return a.caps.KV() }

// Daemon / Media / Device / Storage / Message / Schedule are shortcuts into the
// capability domains; use Capabilities() when you need finer control.
func (a *App) Daemon() *capability.Daemon     { return a.caps.Daemon() }
func (a *App) Media() *capability.Media       { return a.caps.Media() }
func (a *App) Device() *capability.Device     { return a.caps.Device() }
func (a *App) Storage() *capability.Storage   { return a.caps.Storage() }
func (a *App) Message() *capability.Message   { return a.caps.Message() }
func (a *App) Schedule() *capability.Schedule { return a.caps.Schedule() }
func (a *App) Events() *capability.Events     { return a.caps.Events() }

// FS returns the local file access entry point (POSIX passthrough, not via the
// bus).
//
// When the mount table is missing, it returns an error: this means the app
// declared no storage.* permission, or the mount table could not be written
// during deployment. Callers should degrade instead of treating it as fatal — bus
// capabilities are usually still available.
func (a *App) FS() (*appfs.Table, error) {
	a.fsMu.Lock()
	defer a.fsMu.Unlock()
	if a.fsLoaded {
		return a.fsTable, a.fsErr
	}
	a.fsTable, a.fsErr = appfs.Load()
	a.fsLoaded = true
	return a.fsTable, a.fsErr
}

// ReloadFS discards the cache and re-reads the mount table.
//
// A native shared instance's mount table may be refreshed by the daemon (when the
// authorized spaces change); no process restart is needed, one ReloadFS call
// picks up the new directory view.
func (a *App) ReloadFS() (*appfs.Table, error) {
	a.fsMu.Lock()
	a.fsLoaded = false
	a.fsTable, a.fsErr = nil, nil
	a.fsMu.Unlock()
	return a.FS()
}

// State returns the current connection state, suitable for inclusion in the app's
// own health check output.
func (a *App) State() bus.State {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.state
}

// Close closes the bus connection.
func (a *App) Close() error {
	if a.client == nil {
		return nil
	}
	return a.client.Close()
}

// readStoragePools reads the NATIVE_STORAGE_POOL_* variables.
func readStoragePools() map[string]string {
	pools := map[string]string{}
	for _, kv := range os.Environ() {
		idx := strings.IndexByte(kv, '=')
		if idx <= 0 {
			continue
		}
		key, value := kv[:idx], kv[idx+1:]
		if !strings.HasPrefix(key, protocol.EnvStoragePoolPrefix) {
			continue
		}
		name := strings.TrimPrefix(key, protocol.EnvStoragePoolPrefix)
		if name == "" || strings.TrimSpace(value) == "" {
			continue
		}
		pools[name] = value
	}
	if len(pools) == 0 {
		return nil
	}
	return pools
}

// normalizePoolName keeps the same rules as the daemon's storagePoolEnvName.
func normalizePoolName(name string) string {
	name = strings.ToUpper(strings.TrimSpace(name))
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return strings.Trim(b.String(), "_")
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if s := strings.TrimSpace(v); s != "" {
			return s
		}
	}
	return ""
}
